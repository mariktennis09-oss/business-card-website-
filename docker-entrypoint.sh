#!/bin/sh
# Подготовка базы при каждом старте контейнера: миграции, затем сид.
# Обе операции идемпотентны, поэтому «запуск с нуля» и перезапуск дают
# одинаковый результат.
#
# При одной реплике (как в docker-compose) это безопасно и просто. При
# масштабировании до нескольких реплик миграции и сид следовало бы вынести
# в отдельный init-job, выполняемый один раз до старта приложения.
set -e

echo "→ Применяю миграции"
npx prisma migrate deploy --schema prisma/schema.prisma

echo "→ Заполняю базу данными визитки"
node dist/seed/prisma/seed.js

echo "→ Запускаю приложение"
exec node dist/main
